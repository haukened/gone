#!/bin/sh
# Writes the Homebrew formula for the gone CLI (haukened/homebrew-gone,
# Formula/gone.rb) for a release, to standard output. It installs the
# release's prebuilt, signed archives for macOS and Linux, checked against
# the release's SHA256SUMS.
#
#   scripts/homebrew-formula.sh v3.12.0 > Formula/gone.rb
set -eu

tag=${1:?usage: homebrew-formula.sh vX.Y.Z}
case "$tag" in
v[0-9]*.[0-9]*.[0-9]*) ;;
*) echo "homebrew-formula.sh: $tag is not a release tag (vX.Y.Z)" >&2; exit 2 ;;
esac
case "$tag" in *-*) echo "homebrew-formula.sh: $tag is a pre-release; the tap carries stable releases only" >&2; exit 2 ;; esac

base="https://github.com/haukened/gone/releases/download/${tag}"
sums=$(curl -fsSL "${base}/SHA256SUMS")

# sha prints the checksum of one archive, or fails if the release lacks it.
sha() {
	s=$(printf '%s\n' "$sums" | awk -v f="gone_${tag}_$1.tar.gz" '$2 == f || $2 == "*" f { print $1 }')
	[ -n "$s" ] || { echo "homebrew-formula.sh: no gone_${tag}_$1.tar.gz in SHA256SUMS" >&2; exit 1; }
	printf '%s' "$s"
}

cat <<RUBY
# Generated by scripts/homebrew-formula.sh in haukened/gone for ${tag}.
# The release workflow updates it on every stable release; don't edit it here.
class Gone < Formula
  desc "Share a secret exactly once with end-to-end encrypted, one-time links"
  homepage "https://getgone.dev"
  license "AGPL-3.0-only"

  on_macos do
    on_arm do
      url "${base}/gone_${tag}_darwin_arm64.tar.gz"
      sha256 "$(sha darwin_arm64)"
    end
    on_intel do
      url "${base}/gone_${tag}_darwin_amd64.tar.gz"
      sha256 "$(sha darwin_amd64)"
    end
  end

  on_linux do
    on_arm do
      url "${base}/gone_${tag}_linux_arm64.tar.gz"
      sha256 "$(sha linux_arm64)"
    end
    on_intel do
      url "${base}/gone_${tag}_linux_amd64.tar.gz"
      sha256 "$(sha linux_amd64)"
    end
  end

  def install
    bin.install "gone"
  end

  test do
    assert_match "gone v#{version}", shell_output("#{bin}/gone version")
  end
end
RUBY
